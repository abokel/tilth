def aff(name, sci, category, hosts, transmission, env, life, impact, control, symptoms, notes="", beneficial=False):
    obj = {"name": name, "scientific_name": sci, "category": category, "hosts": hosts, "transmission": transmission,
           "envelope": env, "lifecycle": life, "impact": impact, "control": control, "symptoms": symptoms}
    if beneficial:
        obj["beneficial"] = True
    if notes:
        obj["notes"] = notes
    return obj


def env(tmin, topt, tmax, humidity=0, wet=0, smin=0.0, smax=2.0, phmin=3.0, phmax=10.0):
    return {"temp_min": tmin, "temp_opt": topt, "temp_max": tmax, "min_humidity": humidity, "leaf_wetness_hours": wet,
            "soil_moisture_min": smin, "soil_moisture_max": smax, "ph_min": phmin, "ph_max": phmax}


def life(latent, spread, overwinter, years):
    return {"latent_days": latent, "spread_rate": spread, "overwintering": overwinter, "survival_years": years}


def hit(loss, growth=0.0, quality=0.0, kills=False, start=1, end=9, benefit=0.0):
    return {"max_yield_loss": loss, "growth_penalty": growth, "quality_penalty": quality, "can_kill_host": kills,
            "from_stage": start, "to_stage": end, "benefit": benefit}


def ctl(rotation=0, tillage=0.0, resistant=False, methods=()):
    return {"rotation_break_years": rotation, "tillage_reduction": tillage, "resistant_varieties": resistant, "methods": list(methods)}


